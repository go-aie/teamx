import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import p from 'node:path';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {superviseDeployment} from './deploy-linux-remote.mjs';

test('a disconnected follower leaves its worker running; a retry follows one job and preserves its receipt',{timeout:15000},async t=>{
  const root=fs.mkdtempSync(p.join(os.tmpdir(),"teamx-supervisor ' "));
  const mock=p.join(root,'mock'), job=p.join(root,'job'), retry=p.join(root,'retry');
  for(const dir of [mock,job,retry])fs.mkdirSync(dir);
  const marker=p.join(root,'running'), pid=p.join(root,'pid');
  const module=new URL('./deploy-linux-remote.mjs',import.meta.url).href;
  const worker=p.join(root,'worker.mjs');
  fs.writeFileSync(worker,`import fs from 'node:fs';import {saveDeployment} from ${JSON.stringify(module)};
const request=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
fs.writeFileSync(request.job+'/run.log','worker running\\n');
saveDeployment(request.job+'/deployment.json',{status:'preparing'});
await new Promise(resolve=>setTimeout(resolve,2500));
saveDeployment(request.job+'/deployment.json',{status:'built',finished_at:new Date().toISOString(),source_commit:request.commit});
fs.unlinkSync(${JSON.stringify(marker)});
`);
  const launcher=p.join(root,'launch.mjs');
  fs.writeFileSync(launcher,`import fs from 'node:fs';import {spawn} from 'node:child_process';
fs.appendFileSync(${JSON.stringify(p.join(root,'launches'))},'launch\\n');
fs.writeFileSync(${JSON.stringify(marker)},'active');
const child=spawn(process.execPath,[${JSON.stringify(worker)},process.argv.at(-2)],{detached:true,stdio:'ignore'});
fs.writeFileSync(${JSON.stringify(pid)},String(child.pid));child.unref();`);
  const systemctl=p.join(root,'systemctl.mjs');
  fs.writeFileSync(systemctl,`import fs from 'node:fs';const active=fs.existsSync(${JSON.stringify(marker)});console.log(active?'active':'inactive');process.exit(active?0:3);`);
  const quote=s=>"'"+s.replaceAll("'","'\\''")+"'";
  for(const [name,file] of [['systemd-run',launcher],['systemctl',systemctl]])fs.writeFileSync(p.join(mock,name),`#!/bin/sh\nexec ${quote(process.execPath)} ${quote(file)} "$@"\n`,{mode:0o755});
  fs.writeFileSync(p.join(mock,'sudo'),'#!/bin/sh\nif [ "$1" = -n ]; then shift; fi\nexec "$@"\n',{mode:0o755});
  const previous=process.env.PATH;process.env.PATH=mock+':'+previous;
  t.after(()=>{process.env.PATH=previous;if(fs.existsSync(pid)){try{process.kill(Number(fs.readFileSync(pid,'utf8')),'SIGKILL');}catch{}}fs.rmSync(root,{recursive:true,force:true});});
  const request={job,commit:'a'.repeat(40),build_only:true,config:{work_dir:root,server_root:p.join(root,'server')}};
  const file=p.join(job,'request.json');fs.writeFileSync(file,JSON.stringify(request));
  const follower=p.join(root,'follow.mjs');fs.writeFileSync(follower,`import {superviseDeployment} from ${JSON.stringify(module)};import fs from 'node:fs';await superviseDeployment(JSON.parse(fs.readFileSync(process.argv[2],'utf8')),process.argv[2]);`);
  const first=spawn(process.execPath,[follower,file],{stdio:['ignore','pipe','pipe']});
  t.after(()=>{if(first.exitCode===null && first.signalCode===null)first.kill('SIGKILL');});
  let errors='';first.stderr.on('data',b=>{errors+=b;});
  await Promise.race([once(first.stdout,'data'),once(first,'exit').then(()=>{throw Error(errors || 'Follower exited early');})]);
  const exited=once(first,'exit');first.kill('SIGTERM');await exited;
  assert.equal(fs.existsSync(marker),true);
  const next={...request,job:retry};const nextFile=p.join(retry,'request.json');fs.writeFileSync(nextFile,JSON.stringify(next));
  await assert.rejects(superviseDeployment({...next,full_smoke:true},nextFile),/different build\/smoke options/);
  await superviseDeployment(next,nextFile);
  assert.equal(fs.readFileSync(p.join(root,'launches'),'utf8'),'launch\n');
  const receipt=JSON.parse(fs.readFileSync(p.join(retry,'deployment.json'),'utf8'));
  assert.equal(receipt.status,'built');assert.equal(receipt.followed_job,job);
});
