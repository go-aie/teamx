import assert from "node:assert/strict";
import { launch, settle } from "./web_app_harness.mjs";
import { request } from "./web/client.mjs";
const endpoint = process.env.TEAMX_WEB_ENDPOINT;
let call = (path, body) => request(endpoint + path, body);
if (process.env.TEAMX_WEB_TRANSPORT === "stdio") {
  const { createInterface } = await import("node:readline");
  const pending = new Map(); let seq = 0;
  createInterface({ input: process.stdin }).on("line", line => {
    const response = JSON.parse(line), receipt = pending.get(response.id);
    pending.delete(response.id);
    if (response.status === 200) receipt.resolve(response.body);
    else receipt.reject(Object.assign(new Error(response.body.error), { code: response.body.code }));
  });
  call = (path, body) => new Promise((resolve, reject) => {
    const id = ++seq; pending.set(id, { resolve, reject });
    process.stdout.write(JSON.stringify({ id, path, body }) + "\n");
  });
}
const ui = await launch({ request: call });
await ui.el("open-settings").emit("click");
assert.equal(ui.el("settings-dialog").open, true);
await ui.el("connection-new").emit("click");
ui.el("connection-name").value = "HTTP GitLab";
ui.el("connection-url").value = "https://gitlab.invalid";
ui.el("connection-pat").value = "http-only-test-token";
await ui.el("connection-form").emit("submit");
assert.equal(ui.el("connections-feedback").textContent, "连接已保存。");
assert.equal(ui.el("connection-pat").value, "");
assert.equal(ui.el("connection-form").hidden, true);
assert.equal(ui.el("connections-list-view").hidden, false);
await ui.el("connections-list").children[0].emit("click");
await ui.el("connection-verify").emit("click");
assert.equal(ui.el("connection-validation").textContent, "已验证 · @http-user");
assert.match(ui.el("connection-validation").title, /账号 ID 101/);
await ui.el("connection-back").emit("click");
assert.equal(ui.el("connections-list").children.length, 1);
await ui.el("connections-list").children[0].emit("click");
ui.el("connection-name").value = "Renamed HTTP GitLab";
await ui.el("connection-form").emit("submit");
assert.equal(ui.el("connections-feedback").textContent, "连接已保存。");
assert.equal(ui.el("connection-form").hidden, true);
assert.equal(ui.el("connections-list").children.length, 1);
assert.equal(ui.el("connections-list").children[0].children[0].children[0].textContent, "Renamed HTTP GitLab");
await ui.el("connections-list").children[0].emit("click");
await ui.el("connection-delete").emit("click");
assert.equal(ui.el("connections-empty").hidden, false);
assert.equal(ui.el("connections-feedback").textContent, "连接已删除。");
await settle();
assert.equal(JSON.stringify([...ui.saved]).includes("http-only-test-token"), false);
console.error("platform connection UI/API: create, verify, rename, delete passed");
if (process.env.TEAMX_WEB_TRANSPORT === "stdio") process.stdin.destroy();
